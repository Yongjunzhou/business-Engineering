"""余下四份的形式关：列作名词的改字段，动词写全。"""
import io, sys

JOBS = {
    '04-产品数据范例/03-相关方需求.md': [
        ('取一个新选配，核 BOM 件是否全在名录内', '取用一个新选配，核对 BOM 件是否全在名录内', 1),
    ],
    '04-产品数据范例/01-问题与机会清单规范.md': [
        ('写进每条需求的「来源」列。', '写进每条需求的「来源」字段。', 1),
        ('写进「坐标」列。', '写进「坐标」字段。', 1),
        ('的「不成立」列 |', '的「不成立」字段 |', 1),
    ],
    '04-产品数据范例/02-相关方与关切规范.md': [
        ('把关切编号写进每条需求的「来源」列', '把关切编号写进每条需求的「来源」字段', 1),
        ('文档3 的「来源」列、文档4 的确认准则来路', '文档3 的「来源」字段、文档4 的确认准则来路', 1),
        ('写进每条需求的「来源」列；取关切名称', '写进每条需求的「来源」字段；取关用名称', 1),
        ('本规范 3.2.2 的「不成立」列 |', '本规范 3.2.2 的「不成立」字段 |', 1),
    ],
    '04-产品数据范例/03-相关方需求规范.md': [
        ('结论在 5.2 判；', '结论在 5.2 判定；', 1),
        ('强制型关切的原则由文档9 取。', '强制型关切的原则由文档9 取用。', 1),
        ('| 群体当主角色，写「客户」「各方」。', '| 群体当主角色，写出「客户」「各方」。', 1),
        ('术语与 6.2 的「东西」改「对象」「字段与编号」，六处抽象的「件」改点名或改量词',
         '术语与 6.2 的「东西」改作「对象」「字段与编号」，六处把量词当名词用的地方改点名或改量词', 1),
    ],
}

bad = 0
cache = {}
for p, T in JOBS.items():
    t = io.open(p, encoding='utf-8').read()
    cache[p] = t
    for old, new, want in T:
        n = t.count(old)
        if n != want:
            print('✗ %s 命中 %d 处：%s' % (p.split('/')[-1], n, old[:30]))
            bad += 1
            continue
        t = t.replace(old, new)
    cache[p] = t
if bad:
    print('没落 %d 行，未写回。' % bad)
    sys.exit(1)
for p, t in cache.items():
    io.open(p, 'w', encoding='utf-8').write(t)
print('四份已写回。')
