def main():
    t = io.open(P, encoding='utf-8').read()
    bad = 0
    fix = 0
    for old, new, n in T:
        c = t.count(old)
        if c != 1:
            print('✗ 命中 %d 处（要 1）：%s' % (c, old[:36]))
            bad += 1
            continue
        t = t.replace(old, new)
        fix += n
    if bad:
        print('没落 %d 行，未写回。' % bad)
        return 1
    io.open(P, 'w', encoding='utf-8').write(t)
    print('落 %d 行，改到 %d 处单字，已写回。' % (len(T), fix))
    return 0


if __name__ == '__main__':
    sys.exit(main())
