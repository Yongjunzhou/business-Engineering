def apply_all(txt):
    log = []
    for o, n, t in PAIRS:
        if txt.count(o) == 1:
            txt = txt.replace(o, n, 1); log.append('OK   ' + t)
        else:
            log.append('MISS %s（命中 %d）' % (t, txt.count(o)))
    # 附录 D 左列：章级与轴类不该带 §
    txt = re.sub(r'\| § (十[一二三四五六]|[一二三四五六七八九]、|轴[一二三四])', r'| \1', txt)
    # 标题前补空行（凡 ### 上一行非空、非表格、非 ``` 者）
    lines = txt.split('\n'); out = []
    for i, l in enumerate(lines):
        if l.startswith('### ') and out and out[-1].strip() != '' and not out[-1].startswith('|'):
            out.append('')
        out.append(l)
    return '\n'.join(out), log

def main():
    apply = '--apply' in sys.argv
    txt = open(P, encoding='utf-8').read()
    new, log = apply_all(txt)
    n_blank = len([1 for l in new.split('\n')]) - len([1 for l in txt.split('\n')])
    print('\n'.join(log))
    print('空行补入：%d 行' % n_blank)
    if not apply:
        print('（预演，未写）'); return 0
    open(P, 'w', encoding='utf-8', newline='\n').write(new)
    print('已写入')
    return 0

sys.exit(main())
