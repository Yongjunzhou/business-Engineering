def conv_arg(s, m):
    """附录 A「论证」列专用：该列按定义全是本件自引，整列按表换号。"""
    def sub(mm):
        k = mm.group(1)
        v = m.get(k, k)
        return v if v.startswith('附录') else '§' + v
    s = re.sub(r'§(\d+(?:\.\d+)*|十六|十五|十四|十三|十二|十一|十|[一二三四五六七八九])(?![一二三四五六七八九])', sub, s)
    return s

def conv_line(l, m):
    """只换"认得出是本件自引"的号：
       ① 12~16 区间（任何正本都没有第 12 章以上）→ 机械换；
       ② 章级 §一~§十六 → 按章表换；
       ③ 2~7 区间本件自引已逐处判过，只有 6 处 → 用 ANCHORS 显式换。
    """
    if any(k in l for k in EXEMPT):
        return l
    def sub_num(mm):
        k = mm.group(1)
        if not re.match(r'^1[2-6](\.|$)', k):
            return mm.group(0)
        return '§' + m.get(k, k)
    l = re.sub(r'§(\d+(?:\.\d+)*)', sub_num, l)

    def sub_ch(mm):
        pre = l[max(0, mm.start() - 16):mm.start()]
        if any(s in pre for s in STD + ('46 号', '48 号', '42 号', '34 号', '主线')):
            return mm.group(0)
        v = m.get(mm.group(1), mm.group(1))
        return v if v.startswith('附录') else '§' + v
    l = re.sub(r'§(十六|十五|十四|十三|十二|十一|十|[一二三四五六七八九])(?![一二三四五六七八九])', sub_ch, l)
    for old, new, _t in ANCHORS:
        if old in l:
            l = l.replace(old, new)
    return l

